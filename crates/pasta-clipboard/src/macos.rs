//! macOS adapter: poll `NSPasteboard.changeCount` (#13), write with a marker
//! type (#15). See ADR 0005.

use std::sync::atomic::{AtomicBool, AtomicIsize, Ordering};
use std::sync::{Arc, Mutex, RwLock};
use std::thread;
use std::time::Duration;

use objc2::rc::autoreleasepool;
use objc2::runtime::AnyObject;
use objc2_app_kit::{
    NSPasteboard, NSPasteboardContentsOptions, NSPasteboardTypeHTML, NSPasteboardTypeRTF, NSPasteboardTypeString,
    NSRunningApplication, NSWorkspace,
};
use objc2_core_foundation::CFRetained;
use objc2_core_graphics::{CGWindowListCopyWindowInfo, CGWindowListOption, kCGNullWindowID};
use objc2_foundation::{NSArray, NSData, NSDictionary, NSNumber, NSString};
use pasta_core::clip::{Flavors, SourceApp, UNIVERSAL_CLIPBOARD_APP_ID};
use pasta_core::clipboard::{
    AdapterOptions, ClipboardAdapter, ClipboardError, CopySink, LocalCopy, Watch, WriteKind, WriteReceipt,
};
use uuid::Uuid;

use crate::sensitive::{is_password_manager_bundle, is_password_manager_source_url};

/// 250 ms keeps latency low at ~0.1% CPU (ADR 0005).
const POLL_INTERVAL: Duration = Duration::from_millis(250);
/// Pasta's own-write marker. Lost through Universal Clipboard, so the engine
/// also dedupes by content hash.
const MARKER_TYPE: &str = "dev.pasta.origin";
/// nspasteboard.org conventions for items clipboard tools should skip.
const SKIPPED_TYPES: &[&str] =
    &["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];
/// Set on items that arrived through Universal Clipboard.
const REMOTE_CLIPBOARD: &str = UNIVERSAL_CLIPBOARD_APP_ID;
/// How Universal Clipboard items are labelled (ADR 0005).
const UNIVERSAL_CLIPBOARD_LABEL: &str = "iPhone · iCloud";
const CHROMIUM_SOURCE_URL: &str = "org.chromium.source-url";
const CONCEALED_TYPE: &str = "org.nspasteboard.ConcealedType";

type Sink = Arc<dyn Fn(LocalCopy) + Send + Sync>;
type Options = Arc<RwLock<AdapterOptions>>;

#[derive(Default)]
pub struct MacClipboard {
    /// `changeCount` after Pasta's last write, so the watcher skips it.
    own_change_count: Arc<AtomicIsize>,
    options: Options,
}

fn read_options(options: &Options) -> AdapterOptions {
    options.read().unwrap_or_else(std::sync::PoisonError::into_inner).clone()
}

impl MacClipboard {
    pub fn new() -> Self {
        Self::default()
    }
}

impl ClipboardAdapter for MacClipboard {
    fn watch(&self, sink: CopySink) -> Result<Watch, ClipboardError> {
        let sink: Sink = Arc::from(sink);
        let stop = Arc::new(AtomicBool::new(false));
        let own = Arc::clone(&self.own_change_count);
        let options = Arc::clone(&self.options);
        let thread_stop = Arc::clone(&stop);
        let thread = thread::Builder::new()
            .name("pasta-pasteboard".into())
            .spawn(move || poll(&sink, &own, &options, &thread_stop))
            .map_err(|err| ClipboardError::Os(err.to_string()))?;
        let thread = Mutex::new(Some(thread));
        Ok(Watch::new(move || {
            stop.store(true, Ordering::Relaxed);
            if let Some(thread) = thread.lock().ok().and_then(|mut thread| thread.take()) {
                let _ = thread.join();
            }
        }))
    }

    fn write(&self, item_id: Uuid, flavors: &Flavors) -> Result<WriteReceipt, ClipboardError> {
        self.write_as(item_id, flavors, WriteKind::Normal)
    }

    fn write_concealed(&self, item_id: Uuid, flavors: &Flavors) -> Result<WriteReceipt, ClipboardError> {
        self.write_as(item_id, flavors, WriteKind::Concealed)
    }

    fn configure(&self, options: &AdapterOptions) {
        *self.options.write().unwrap_or_else(std::sync::PoisonError::into_inner) = options.clone();
    }

    fn expire(&self, receipt: &WriteReceipt) -> Result<(), ClipboardError> {
        autoreleasepool(|_| {
            let pasteboard = NSPasteboard::generalPasteboard();
            if receipt.change_count == Some(pasteboard.changeCount() as i64) {
                pasteboard.clearContents();
            }
        });
        Ok(())
    }
}

impl MacClipboard {
    fn write_as(&self, item_id: Uuid, flavors: &Flavors, kind: WriteKind) -> Result<WriteReceipt, ClipboardError> {
        let bridge = read_options(&self.options).icloud_bridge && kind == WriteKind::Normal;
        autoreleasepool(|_| {
            let pasteboard = NSPasteboard::generalPasteboard();
            if bridge {
                pasteboard.clearContents();
            } else {
                // Keeps the item off Universal Clipboard (#41): only this Mac sees it.
                pasteboard.prepareForNewContentsWithOptions(NSPasteboardContentsOptions::CurrentHostOnly);
            }
            let ok =
                pasteboard.setString_forType(&NSString::from_str(&flavors.plain), unsafe { NSPasteboardTypeString });
            if !ok {
                return Err(ClipboardError::Os("NSPasteboard refused the text".into()));
            }
            if let Some(html) = &flavors.html {
                pasteboard.setString_forType(&NSString::from_str(html), unsafe { NSPasteboardTypeHTML });
            }
            if let Some(rtf) = &flavors.rtf {
                let data = NSData::with_bytes(rtf.as_bytes());
                pasteboard.setData_forType(Some(&data), unsafe { NSPasteboardTypeRTF });
            }
            pasteboard.setString_forType(&NSString::from_str("1"), &NSString::from_str(MARKER_TYPE));
            if kind == WriteKind::Concealed {
                // Clipboard managers that follow nspasteboard.org skip it.
                pasteboard.setString_forType(&NSString::from_str("1"), &NSString::from_str(CONCEALED_TYPE));
            }
            let count = pasteboard.changeCount();
            self.own_change_count.store(count, Ordering::SeqCst);
            Ok(WriteReceipt { item_id, history_id: None, change_count: Some(count as i64) })
        })
    }
}

fn poll(sink: &Sink, own: &AtomicIsize, options: &Options, stop: &AtomicBool) {
    let mut last = autoreleasepool(|_| NSPasteboard::generalPasteboard().changeCount());
    while !stop.load(Ordering::Relaxed) {
        // A plain sleep: this thread has no run-loop sources, so `NSRunLoop::runUntilDate`
        // would return at once and spin. The app's main thread keeps NSWorkspace current.
        thread::sleep(POLL_INTERVAL);
        autoreleasepool(|_| {
            let pasteboard = NSPasteboard::generalPasteboard();
            let count = pasteboard.changeCount();
            if count == last {
                return;
            }
            last = count;
            if count == own.load(Ordering::SeqCst) {
                return;
            }
            if let Some(copy) = read(&pasteboard, &read_options(options)) {
                sink(copy);
            }
        });
    }
    tracing::debug!("pasteboard watcher stopped");
}

fn read(pasteboard: &NSPasteboard, options: &AdapterOptions) -> Option<LocalCopy> {
    let types: Vec<String> = pasteboard.types().map(|types| types.iter().map(|t| t.to_string()).collect())?;
    let has = |name: &str| types.iter().any(|t| t == name);
    if has(MARKER_TYPE) {
        return None; // Pasta's own write
    }
    if options.skip_sensitive
        && let Some(marker) = SKIPPED_TYPES.iter().find(|t| has(t))
    {
        tracing::debug!(marker, "skipped a copy marked sensitive");
        return None;
    }
    let source_app = if has(REMOTE_CLIPBOARD) {
        // The frontmost app is unrelated to a Universal Clipboard item (ADR 0005). The
        // engine keeps it on this Mac unless the bridge is on (#41).
        Some(SourceApp { name: UNIVERSAL_CLIPBOARD_LABEL.into(), id: REMOTE_CLIPBOARD.into() })
    } else {
        let app = frontmost_app();
        if let Some(app) = &app {
            if options.skip_sensitive && is_password_manager_bundle(&app.id) {
                tracing::debug!(app = %app.id, "skipped a copy from a password manager");
                return None;
            }
            if options.excluded_apps.iter().any(|id| id.eq_ignore_ascii_case(&app.id)) {
                tracing::debug!(app = %app.id, "skipped a copy from an excluded app");
                return None;
            }
        }
        app
    };
    if options.skip_sensitive
        && has(CHROMIUM_SOURCE_URL)
        && pasteboard
            .stringForType(&NSString::from_str(CHROMIUM_SOURCE_URL))
            .is_some_and(|url| is_password_manager_source_url(&url.to_string()))
    {
        tracing::debug!("skipped a copy from a password-manager extension");
        return None;
    }
    let plain = pasteboard.stringForType(unsafe { NSPasteboardTypeString })?.to_string();
    if plain.is_empty() {
        return None;
    }
    let html = pasteboard.stringForType(unsafe { NSPasteboardTypeHTML }).map(|html| html.to_string());
    let rtf = pasteboard
        .dataForType(unsafe { NSPasteboardTypeRTF })
        .map(|data| String::from_utf8_lossy(&data.to_vec()).into_owned());
    Some(LocalCopy { flavors: Flavors { plain, html, rtf }, source_app })
}

/// The app in front when the copy was seen. Also used by the panel (#39).
///
/// Asks the WindowServer for the owner of the frontmost normal window rather
/// than trusting `NSWorkspace.frontmostApplication`: that value is cached and
/// refreshed by the main run loop, and read from this thread in the app it
/// lagged behind, so copies in Passwords and Proton Pass were attributed to
/// the previous app and synced (#13). NSWorkspace is the fallback when no app
/// window is on screen.
pub(crate) fn frontmost_app() -> Option<SourceApp> {
    let app = frontmost_window_pid()
        .and_then(NSRunningApplication::runningApplicationWithProcessIdentifier)
        .or_else(|| NSWorkspace::sharedWorkspace().frontmostApplication())?;
    let name = app.localizedName().map(|name| name.to_string()).unwrap_or_default();
    let id = app.bundleIdentifier().map(|id| id.to_string()).unwrap_or_default();
    Some(SourceApp { name, id })
}

/// Regular (Dock) apps that are running, except Pasta.
pub(crate) fn running_apps() -> Vec<SourceApp> {
    autoreleasepool(|_| {
        let own_pid = i32::try_from(std::process::id()).unwrap_or_default();
        NSWorkspace::sharedWorkspace()
            .runningApplications()
            .iter()
            .filter(|app| {
                app.activationPolicy() == objc2_app_kit::NSApplicationActivationPolicy::Regular
                    && app.processIdentifier() != own_pid
            })
            .map(|app| SourceApp {
                name: app.localizedName().map(|name| name.to_string()).unwrap_or_default(),
                id: app.bundleIdentifier().map(|id| id.to_string()).unwrap_or_default(),
            })
            .collect()
    })
}

/// Process id of the frontmost on-screen window at the normal level (layer 0),
/// skipping Pasta's own windows.
pub(crate) fn frontmost_window_pid() -> Option<i32> {
    let options = CGWindowListOption::OptionOnScreenOnly | CGWindowListOption::ExcludeDesktopElements;
    let windows = CGWindowListCopyWindowInfo(options, kCGNullWindowID)?;
    // A CFArray of CFDictionary is toll-free bridged to NSArray<NSDictionary>; `windows`
    // keeps it alive for the borrow. Ordered front to back.
    let windows: &NSArray<NSDictionary<NSString, AnyObject>> =
        unsafe { &*CFRetained::as_ptr(&windows).as_ptr().cast() };
    let own_pid = i32::try_from(std::process::id()).unwrap_or_default();
    windows.iter().find_map(|window| {
        let number = |key: &str| {
            let value = window.objectForKey(&NSString::from_str(key))?;
            Some(value.downcast::<NSNumber>().ok()?.intValue())
        };
        let pid = number("kCGWindowOwnerPID")?;
        (number("kCGWindowLayer")? == 0 && pid != own_pid).then_some(pid)
    })
}
