//! macOS adapter: poll `NSPasteboard.changeCount` (#13), write with a marker
//! type (#15). See ADR 0005.

use std::sync::atomic::{AtomicBool, AtomicIsize, Ordering};
use std::sync::{Arc, Mutex};
use std::thread;
use std::time::Duration;

use objc2::rc::autoreleasepool;
use objc2_app_kit::{NSPasteboard, NSPasteboardTypeHTML, NSPasteboardTypeRTF, NSPasteboardTypeString, NSWorkspace};
use objc2_foundation::{NSData, NSString};
use pasta_core::clip::{Flavors, SourceApp};
use pasta_core::clipboard::{ClipboardAdapter, ClipboardError, CopySink, LocalCopy, Watch, WriteReceipt};
use uuid::Uuid;

use crate::sensitive::{is_password_manager_bundle, is_password_manager_source_url};

/// 250 ms keeps latency low at ~0.1% CPU (ADR 0005).
const POLL_INTERVAL: Duration = Duration::from_millis(250);
/// Pasta's own-write marker. Lost through Universal Clipboard, so the engine
/// also dedupes by content hash.
const MARKER_TYPE: &str = "dev.pasta.origin";
/// nspasteboard.org conventions for items clipboard tools should skip.
const SKIPPED_TYPES: &[&str] =
    &["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];
/// Set on items that arrived through Universal Clipboard.
const REMOTE_CLIPBOARD: &str = "com.apple.is-remote-clipboard";
const CHROMIUM_SOURCE_URL: &str = "org.chromium.source-url";

type Sink = Arc<dyn Fn(LocalCopy) + Send + Sync>;

#[derive(Default)]
pub struct MacClipboard {
    /// `changeCount` after Pasta's last write, so the watcher skips it.
    own_change_count: Arc<AtomicIsize>,
}

impl MacClipboard {
    pub fn new() -> Self {
        Self::default()
    }
}

impl ClipboardAdapter for MacClipboard {
    fn watch(&self, sink: CopySink) -> Result<Watch, ClipboardError> {
        let sink: Sink = Arc::from(sink);
        let stop = Arc::new(AtomicBool::new(false));
        let own = Arc::clone(&self.own_change_count);
        let thread_stop = Arc::clone(&stop);
        let thread = thread::Builder::new()
            .name("pasta-pasteboard".into())
            .spawn(move || poll(&sink, &own, &thread_stop))
            .map_err(|err| ClipboardError::Os(err.to_string()))?;
        let thread = Mutex::new(Some(thread));
        Ok(Watch::new(move || {
            stop.store(true, Ordering::Relaxed);
            if let Some(thread) = thread.lock().ok().and_then(|mut thread| thread.take()) {
                let _ = thread.join();
            }
        }))
    }

    fn write(&self, item_id: Uuid, flavors: &Flavors) -> Result<WriteReceipt, ClipboardError> {
        autoreleasepool(|_| {
            let pasteboard = NSPasteboard::generalPasteboard();
            pasteboard.clearContents();
            let ok =
                pasteboard.setString_forType(&NSString::from_str(&flavors.plain), unsafe { NSPasteboardTypeString });
            if !ok {
                return Err(ClipboardError::Os("NSPasteboard refused the text".into()));
            }
            if let Some(html) = &flavors.html {
                pasteboard.setString_forType(&NSString::from_str(html), unsafe { NSPasteboardTypeHTML });
            }
            if let Some(rtf) = &flavors.rtf {
                let data = NSData::with_bytes(rtf.as_bytes());
                pasteboard.setData_forType(Some(&data), unsafe { NSPasteboardTypeRTF });
            }
            pasteboard.setString_forType(&NSString::from_str("1"), &NSString::from_str(MARKER_TYPE));
            let count = pasteboard.changeCount();
            self.own_change_count.store(count, Ordering::SeqCst);
            Ok(WriteReceipt { item_id, history_id: None, change_count: Some(count as i64) })
        })
    }

    fn expire(&self, receipt: &WriteReceipt) -> Result<(), ClipboardError> {
        autoreleasepool(|_| {
            let pasteboard = NSPasteboard::generalPasteboard();
            if receipt.change_count == Some(pasteboard.changeCount() as i64) {
                pasteboard.clearContents();
            }
        });
        Ok(())
    }
}

fn poll(sink: &Sink, own: &AtomicIsize, stop: &AtomicBool) {
    let mut last = autoreleasepool(|_| NSPasteboard::generalPasteboard().changeCount());
    while !stop.load(Ordering::Relaxed) {
        // A plain sleep: this thread has no run-loop sources, so `NSRunLoop::runUntilDate`
        // would return at once and spin. The app's main thread keeps NSWorkspace current.
        thread::sleep(POLL_INTERVAL);
        autoreleasepool(|_| {
            let pasteboard = NSPasteboard::generalPasteboard();
            let count = pasteboard.changeCount();
            if count == last {
                return;
            }
            last = count;
            if count == own.load(Ordering::SeqCst) {
                return;
            }
            if let Some(copy) = read(&pasteboard) {
                sink(copy);
            }
        });
    }
    tracing::debug!("pasteboard watcher stopped");
}

fn read(pasteboard: &NSPasteboard) -> Option<LocalCopy> {
    let types: Vec<String> = pasteboard.types().map(|types| types.iter().map(|t| t.to_string()).collect())?;
    let has = |name: &str| types.iter().any(|t| t == name);
    if let Some(marker) = SKIPPED_TYPES.iter().find(|t| has(t)) {
        tracing::debug!(marker, "skipped a copy marked sensitive");
        return None;
    }
    if has(MARKER_TYPE) {
        return None; // Pasta's own write
    }
    let source_app = if has(REMOTE_CLIPBOARD) {
        // The frontmost app is unrelated to a Universal Clipboard item (ADR 0005).
        Some(SourceApp { name: "iCloud".into(), id: REMOTE_CLIPBOARD.into() })
    } else {
        let app = frontmost_app();
        if let Some(app) = &app
            && is_password_manager_bundle(&app.id)
        {
            tracing::debug!(app = %app.id, "skipped a copy from a password manager");
            return None;
        }
        app
    };
    if has(CHROMIUM_SOURCE_URL)
        && pasteboard
            .stringForType(&NSString::from_str(CHROMIUM_SOURCE_URL))
            .is_some_and(|url| is_password_manager_source_url(&url.to_string()))
    {
        tracing::debug!("skipped a copy from a password-manager extension");
        return None;
    }
    let plain = pasteboard.stringForType(unsafe { NSPasteboardTypeString })?.to_string();
    if plain.is_empty() {
        return None;
    }
    let html = pasteboard.stringForType(unsafe { NSPasteboardTypeHTML }).map(|html| html.to_string());
    let rtf = pasteboard
        .dataForType(unsafe { NSPasteboardTypeRTF })
        .map(|data| String::from_utf8_lossy(&data.to_vec()).into_owned());
    Some(LocalCopy { flavors: Flavors { plain, html, rtf }, source_app })
}

fn frontmost_app() -> Option<SourceApp> {
    let app = NSWorkspace::sharedWorkspace().frontmostApplication()?;
    let name = app.localizedName().map(|name| name.to_string()).unwrap_or_default();
    let id = app.bundleIdentifier().map(|id| id.to_string()).unwrap_or_default();
    Some(SourceApp { name, id })
}
